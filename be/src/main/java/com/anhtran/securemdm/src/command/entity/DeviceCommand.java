package com.anhtran.securemdm.src.command.entity;

import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import org.springframework.data.annotation.Id;
import org.springframework.data.annotation.ReadOnlyProperty;
import org.springframework.data.annotation.Transient;
import org.springframework.data.domain.Persistable;
import org.springframework.data.relational.core.mapping.Table;

@Getter
@Setter
@Builder
@NoArgsConstructor
@AllArgsConstructor
@Table("device_commands")
public class DeviceCommand implements Persistable<String> {
  @Id private String id;
  private String organizationId;
  private String deviceId;
  private String createdBy;
  private String type;
  private String payloadJson;
  private String requestHash;
  private String idempotencyKey;
  private String status;
  private String signedCommand;
  private Integer attempts;
  private String currentAttemptId;
  private Long leaseUntil;
  private Long createdAt;
  private Long expiresAt;
  private Long completedAt;
  private String resultJson;

  /** device_commands.queue_order is AUTO_INCREMENT; never written by the application. */
  @ReadOnlyProperty private Long queueOrder;

  /** Ids are generated by the application, so inserts must be flagged explicitly. */
  @Transient @Builder.Default private boolean newEntity = false;

  @Override
  public String getId() {
    return id;
  }

  @Override
  public boolean isNew() {
    return newEntity;
  }
}
