package com.anhtran.securemdm.src.identity.entity;

import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import org.springframework.data.annotation.Id;
import org.springframework.data.annotation.Transient;
import org.springframework.data.domain.Persistable;
import org.springframework.data.relational.core.mapping.Table;

@Getter
@Setter
@Builder
@NoArgsConstructor
@AllArgsConstructor
@Table("refresh_tokens")
public class RefreshToken implements Persistable<String> {
  @Id private String tokenHash;
  private String sessionId;
  private Long usedAt;

  /** Ids are generated by the application, so inserts must be flagged explicitly. */
  @Transient @Builder.Default private boolean newEntity = false;

  @Override
  public String getId() {
    return tokenHash;
  }

  @Override
  public boolean isNew() {
    return newEntity;
  }
}
